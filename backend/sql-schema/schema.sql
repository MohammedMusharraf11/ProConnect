-- Trigger: Increment post likes count when a like is added
DELIMITER //
CREATE TRIGGER after_post_like_insert
AFTER INSERT ON POST_LIKES
FOR EACH ROW
BEGIN
    UPDATE POSTS 
    SET LIKES_COUNT = LIKES_COUNT + 1 
    WHERE POST_ID = NEW.POST_ID;
    
    -- Log activity
    INSERT INTO USER_ACTIVITY (USER_ID, ACTIVITY_TYPE, REFERENCE_ID, ACTIVITY_TEXT)
    VALUES (NEW.USER_ID, 'like_post', NEW.POST_ID, 'Liked a post');
END//
DELIMITER ;

-- Trigger: Decrement post likes count when a like is removed
DELIMITER //
CREATE TRIGGER after_post_like_delete
AFTER DELETE ON POST_LIKES
FOR EACH ROW
BEGIN
    UPDATE POSTS 
    SET LIKES_COUNT = GREATEST(LIKES_COUNT - 1, 0)
    WHERE POST_ID = OLD.POST_ID;
END//
DELIMITER ;

