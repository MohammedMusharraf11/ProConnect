AFTER INSERT ON POSTS
FOR EACH ROW
BEGIN
    INSERT INTO USER_ACTIVITY (USER_ID, ACTIVITY_TYPE, REFERENCE_ID, ACTIVITY_TEXT)
    VALUES (NEW.USER_ID, 'post', NEW.POST_ID, COALESCE(NEW.TITLE, SUBSTRING(NEW.CONTENT, 1, 100)));
END//
